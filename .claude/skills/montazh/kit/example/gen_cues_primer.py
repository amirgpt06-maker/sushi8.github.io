"""Пример: сценарий ролика-образца (example/primer-rolika.mp4), записанный ТОЛЬКО функциями библиотеки templates/scenes.py.
Голос: «Этот ролик смонтировал не человек. Монтажёр взял бы за такое от пяти тысяч. Я заплатил ноль. Вот эта анимация — ИИ.
Этот переход — ИИ. Даже звук, который ты сейчас слышишь, — это ИИ. Единственное, что здесь моё, — голос. Всё это — один промпт.
Я его собрал, протестировал и теперь делаю так любые ролики. Хочешь так же? Напиши ЭППЛ в комментариях — я пришлю тебе, как это повторить».
Пауза после «слышишь» удлинена на 1.6 с (tools/extend_pause.py) — под звуковое шоу.
Распознавание пишет «ИИ» то как «ии», то как «и», а «пришлю тебе» как «прошу тебе» — такие места берём по соседним словам (after=…)."""
import os
import sys

sys.path.insert(0, os.environ.get("SKILL_TEMPLATES", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "templates")))
from scenes import *  # noqa: F401,F403

HERE = os.environ.get("PROJECT", os.path.dirname(os.path.abspath(__file__)))
load(HERE)
TH = os.path.join(HERE, "thumbs")

# 1. «Этот ролик смонтировал не человек» — иконка Claude, камера въезжает, волна снизу, уход белым кругом
s2 = at("монтажер")
scene_intro([("Этот", at("этот")), ("ролик", at("ролик"))], end=s2 - 0.05, pill_text="смонтировал", pill_t=at("смонтировал"),
            small_words=[("не", at("не")), ("человек", at("человек"))])

# 2. «Монтажёр взял бы за такое от пяти тысяч. Я заплатил ноль» — виджет с ценой, зачёркивание, 0 ₽
e2 = at("вот") - 0.33
heading([("Монтажёр", s2), ("взял", at("взял")), ("бы", at("бы"))], end=e2, move=(at("такое") + 0.13, 330, 0.7),
        lines_extra=[subline([("за", at("за")), ("такое", at("такое")), ("от", at("от")), ("пяти", at("пяти")), ("тысяч", at("тысяч"))], size=60)], size=104)
scene_number("МОНТАЖЁР", "5 000 ₽", t_card=at("пяти"), end=e2 + 0.12, num2="0 ₽", t_strike=at("заплатил") + 0.05, t_swap=at("ноль"))
text_line([("Я", at("я")), ("заплатил", at("заплатил"))], end=e2, y=1265)
sfx(at("тысяч"), "wbclick", 0.7); sfx(e2 - 0.33, "wbwhoosh", 0.8)

# 3. «Вот эта анимация — ИИ» — подписка в Instagram, нажатие на «ИИ»
t_ai1 = at(("ии", "и"), after=at("анимация"))
e3 = t_ai1 + 0.91
heading([("Вот", at("вот")), ("эта", at("эта")), ("анимация", at("анимация"))], end=e3, size=100, move=(at("вот") + 0.12, 330), exit="drop", exitDur=0.45)
scene_follow(at("анимация") - 0.04, e3, t_btn=at("анимация") + 0.06, t_card=at("анимация") + 0.41, t_press=t_ai1, name="saidulaev.ai", sub="Амирхан | Вайбкодинг")
pill("ИИ", t_ai1, e3, s=None)
sfx(e3 - 0.45, "wbwhoosh", 0.7)

# 4. «Этот переход — ИИ» — стеклянная капля, «ИИ» проявляется внутри неё
t4 = at("этот", 2); t_ai2 = at(("ии", "и"), after=at("переход"))
wave(t4 - 0.08, t_ai2 + 0.11, frm="top", h=420, rise=0.5, fall=0.3)
heading([("Этот", t4), ("переход", at("переход"))], end=t_ai2 + 0.03, size=120, enter="tilt", exit="blur", exitDur=0.32, key_sfx=False)
scene_drop(at("переход") + 0.23, t_ai2)     # капля стартует, когда «переход» уже на экране, — к «ИИ» успевает раздуться
big_word("ИИ", t_ai2, t_ai2 + 0.69)
sfx(t4 - 0.08, "wbslide", 0.55); sfx(t_ai2, "wbpop", 0.9); sfx(t_ai2 + 0.36, "wbslide", 0.55)

# 5. «Даже звук, который ты сейчас слышишь — это ИИ» — звуковое шоу в удлинённой паузе
t_eto = at("это", after=at("слышишь")); e5 = t_eto + 1.16
heading([("Даже", at("даже")), ("звук,", at("звук"))], end=e5, size=116, move=(at("слышишь") + 0.27, 330), exit="left", exitDur=0.45, step=0.045,
        lines_extra=[subline([("который", at("который")), ("ты", at("ты")), ("сейчас", at("сейчас")), ("слышишь —", at("слышишь"))], dy=128, size=58)])
sfx(at("звук"), "tagpop", 0.5)
scene_sound_show(end_of("слышишь") - 0.04, t_eto, end=e5)
text_line([("это", t_eto)], end=e5, y=1270, exit="left")
pill("ИИ", at(("ии", "и"), after=t_eto), e5, pos=(540, 1360), exit="left", gain=0.85)
sfx(e5 - 0.45, "wbwhoosh", 0.8)

# 6. «Единственное, что здесь моё — голос» — тишина эффектов, волна строго по голосу, выделение «голос»
t6 = at("единственная"); e6 = at("все") - 0.45
heading([("Единственное,", t6)], end=e6, y=330, size=100, exit="drop", exitDur=0.45, step=0.035,
        lines_extra=[subline([("что", at("что")), ("здесь", at("здесь")), ("моё —", at("мое"))], dy=118, size=64)])
scene_voice_card(t6 - 0.10, e6)
select("голос", at("голос") - 0.10, e6)
sfx(e6 - 0.45, "wbwhoosh", 0.75)

# 7. «Всё это — один промпт. Я его собрал, протестировал и теперь делаю так любые ролики. Хочешь так же?» — промпт, чипы, ролики
t7 = at("все"); e7 = at("напиши") - 0.02
wave(t7 - 0.05, e7, h=300)
scene_prompt("Смонтируй ролик под мой голос в стиле Apple: текст по словам, переходы, звуки", t7 + 0.05, at("и", after=at("протестировал")) + 0.35,
             t_type=t7 + 0.15, t_type_end=at("промт") - 0.04, t_send=at("промт"),
             chips=[("голос", at("я", after=at("промт")), at("протестировал") + 0.10), ("стиль", at("его") + 0.05, at("протестировал") + 0.28),
                    ("звуки", at("собрал") - 0.02, at("протестировал") + 0.46), ("переходы", at("собрал") + 0.23, at("протестировал") + 0.64)])
heading([("Всё", t7), ("это —", at("это", after=t7 - 0.01)), ("один", at("один"))], end=at("я", after=at("промт")) - 0.09, y=330, size=96, exit="blur", exitDur=0.25)
pill("промпт", at("промт"), at("я", after=at("промт")) - 0.09, pos=(540, 452), size=54, exit="blur", s=None)
heading([("Я", at("я", after=at("промт"))), ("его", at("его")), ("собрал,", at("собрал"))], end=at("протестировал") - 0.05, y=330, size=96, exit="blur", exitDur=0.2, key_sfx=False)
heading([("протестировал,", at("протестировал"))], end=at("протестировал") + 1.10, y=330, size=96, exit="blur", exitDur=0.2, step=0.035, key_sfx=False)
t_i = at("и", after=at("протестировал"))
heading([("и", t_i), ("теперь", at("теперь")), ("делаю", at("делаю")), ("так", at("так"))], end=at("хочешь") - 0.06, y=300, size=84, exit="blur", exitDur=0.2,
        step=0.035, key_sfx=False, lines_extra=[{"words": W(("любые", at("любые")), ("ролики.", at("ролики"))), "size": 84, "weight": 700, "ls": -0.04, "step": 0.035, "y": 100}])
sfx(t_i, "wbslide", 0.5)
if os.path.exists(os.path.join(TH, "r0.jpg")):
    scene_reels([(os.path.join(TH, f"r{i}.jpg"), t) for i, t in enumerate([at("делаю"), at("так"), at("любые"), at("ролики")])], end=e7)
select("Хочешь так же?", at("хочешь") - 0.06, e7, pos=(540, 380), size=82, exit="erase")
sfx(e7 - 0.45, "wbwhoosh", 0.8)

# 8. «Напиши ЭППЛ в комментариях — я пришлю тебе, как это повторить» — призыв, стрелка, док-кнопка
t8 = at("напиши"); end = P["dur"]
scene_cta(("Напиши", t8), "ЭППЛ", at("эппл"), [("в", at("в", after=t8)), ("комментариях", at("комментариях"))], end=end - 0.17,
          t_arrow=at("комментариях") + 0.51,
          dock_words=[("я", at("я", after=at("комментариях"))), ("пришлю", at("прошу")), ("тебе,", at("тебе"))],
          swap_words=[("как", at("как")), ("это", at("это", after=at("как") - 0.01)), ("повторить", at("повторить"))])
sfx(end - 0.67, "wbslide", 0.5)

save()
